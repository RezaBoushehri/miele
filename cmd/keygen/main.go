// Command keygen is the owner-only licensing tool for the miele cutting app.
//
//	keygen init                     create a key pair; embed the public key in the build
//	keygen list                     list plugged-in removable drives and their serials
//	keygen issue -drive E: -name X  write a signed license onto the flash drive
//
// The private key (private.key) must stay secret and must NOT be committed or shared.
// Anyone with it can mint licenses. See docs/SECURITY.md.
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"miele/internal/license"
)

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	switch os.Args[1] {
	case "init":
		cmdInit(os.Args[2:])
	case "list":
		cmdList(os.Args[2:])
	case "issue":
		cmdIssue(os.Args[2:])
	case "-h", "--help", "help":
		usage()
	default:
		fmt.Fprintf(os.Stderr, "unknown command %q\n\n", os.Args[1])
		usage()
	}
}

func usage() {
	fmt.Fprint(os.Stderr, `keygen — ابزار ساخت کلید و مجوز (مخصوص صاحب نرم‌افزار)

دستورها:
  init    ساخت کلید خصوصی/عمومی و قراردادن کلید عمومی در برنامه
  list    نمایش فلش‌های متصل و شماره‌سریال سخت‌افزاری آن‌ها
  issue   ساخت فایل مجوز امضاشده روی فلش

نمونه:
  keygen init
  keygen list
  keygen issue -drive E: -name "Woodworks Co" -days 365
`)
	os.Exit(2)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "error:", err)
	os.Exit(1)
}

func cmdInit(args []string) {
	fs := flag.NewFlagSet("init", flag.ExitOnError)
	keyPath := fs.String("key", "private.key", "where to save the secret private key")
	pubGo := fs.String("embed", filepath.Join("internal", "license", "pubkey.go"),
		"source file to write the public key into")
	force := fs.Bool("force", false, "overwrite an existing private key")
	fs.Parse(args)

	if _, err := os.Stat(*keyPath); err == nil && !*force {
		fatal(fmt.Errorf("%s already exists; use -force to overwrite (this invalidates all existing licenses)", *keyPath))
	}
	pub, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*keyPath, []byte(hex.EncodeToString(priv)+"\n"), 0600); err != nil {
		fatal(err)
	}
	pubHex := hex.EncodeToString(pub)
	if err := writePubKey(*pubGo, pubHex); err != nil {
		fatal(err)
	}
	fmt.Printf("کلید خصوصی ذخیره شد: %s  (این فایل را محرمانه نگه دارید و هرگز منتشر نکنید)\n", *keyPath)
	fmt.Printf("کلید عمومی در %s قرار گرفت.\n", *pubGo)
	fmt.Printf("public key: %s\n\nحالا برنامه را دوباره build کنید.\n", pubHex)
}

func writePubKey(path, pubHex string) error {
	content := fmt.Sprintf(`package license

// PublicKeyHex is the Ed25519 public key this build trusts, as 64 hex chars.
// Generated by "keygen init". The matching private key is kept secret by the owner.
var PublicKeyHex = %q
`, pubHex)
	return os.WriteFile(path, []byte(content), 0644)
}

func cmdList(args []string) {
	drives := license.RemovableDrives()
	if len(drives) == 0 {
		fmt.Println("هیچ فلش متصلی پیدا نشد.")
		return
	}
	for _, d := range drives {
		serial, err := license.DriveSerial(d)
		if err != nil {
			fmt.Printf("%s  (سریال خوانده نشد: %v)\n", d, err)
			continue
		}
		fmt.Printf("%s  serial=%s\n", d, serial)
	}
}

func cmdIssue(args []string) {
	fs := flag.NewFlagSet("issue", flag.ExitOnError)
	drive := fs.String("drive", "", "removable drive to bind to and write the license onto, e.g. E:")
	serial := fs.String("serial", "", "bind to this serial instead of reading a drive")
	name := fs.String("name", "", "customer name")
	days := fs.Int("days", 0, "validity in days (0 = never expires)")
	keyPath := fs.String("key", "private.key", "the secret private key file")
	out := fs.String("out", "", "output path (default: <drive>\\"+license.FileName+")")
	fs.Parse(args)

	if *name == "" {
		fatal(fmt.Errorf("-name is required"))
	}
	priv, err := loadPrivate(*keyPath)
	if err != nil {
		fatal(err)
	}
	ser := strings.TrimSpace(*serial)
	if ser == "" {
		if *drive == "" {
			fatal(fmt.Errorf("provide -drive or -serial"))
		}
		ser, err = license.DriveSerial(*drive)
		if err != nil {
			fatal(err)
		}
	}
	lic := license.License{
		Serial:   ser,
		Customer: *name,
		Issued:   time.Now().UTC().Truncate(24 * time.Hour),
	}
	if *days > 0 {
		lic.Expiry = lic.Issued.AddDate(0, 0, *days)
	}
	data, err := lic.Sign(priv)
	if err != nil {
		fatal(err)
	}
	dst := *out
	if dst == "" {
		if *drive == "" {
			fatal(fmt.Errorf("-out is required when -drive is not given"))
		}
		dst = strings.TrimRight(*drive, `\`) + `\` + license.FileName
	}
	if err := os.WriteFile(dst, data, 0644); err != nil {
		fatal(err)
	}
	fmt.Printf("مجوز ساخته شد: %s\n  مشتری: %s\n  سریال: %s\n", dst, lic.Customer, ser)
	if lic.Expiry.IsZero() {
		fmt.Println("  انقضا: ندارد")
	} else {
		fmt.Printf("  انقضا: %s\n", lic.Expiry.Format("2006-01-02"))
	}
}

func loadPrivate(path string) (ed25519.PrivateKey, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("cannot read private key: %w (run `keygen init` first)", err)
	}
	b, err := hex.DecodeString(strings.TrimSpace(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("private key is not valid hex: %w", err)
	}
	if len(b) != ed25519.PrivateKeySize {
		return nil, fmt.Errorf("private key has wrong length")
	}
	return ed25519.PrivateKey(b), nil
}
